int	ft_atoi(const char *nptr)
{
	int		i;
	int		sign;
	long	n;

	i = 0;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	sign = 1;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i++] == '-')
			sign = -1;
	}
	n = 0;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		if (sign == 1 && (n > 922337203685477580
				|| (n == 922337203685477580 && nptr[i] - '0' > 7)))
			return (-1);
		if (sign == -1 && (n > 922337203685477580
				|| (n == 922337203685477580 && nptr[i] - '0' > 8)))
			return (0);
		n = n * 10 + (nptr[i++] - '0');
	}
	return (n * sign);
}
